/** End-of-chapter capture-the-flag lab with live validation, reset, and flag copying. */
export function Lab({
  title,
  archetype = "build-it",
  difficulty = "guided",
  points = 50,
  hintCost = 10,
  objective,
  starter,
  hints = [],
  verifier,
  verify,
  expect,
  flag,
  children,
  onCapture,
}: {
  title: string;
  archetype?: Archetype;
  difficulty?: "guided" | "unscaffolded";
  points?: number;
  hintCost?: number;
  objective?: string;
  starter?: string;
  hints?: string[];
  verifier?: string;
  verify?: VerifyTier;
  expect?: string; // substring stdout must contain on a clean run to unlock the flag
  flag: string;
  children?: ReactNode;
  onCapture?: (flag: string, hintsUsed: number) => void;
}) {
  const [revealed, setRevealed] = useState(0);
  const [captured, setCaptured] = useState(false);
  const [copiedFlag, setCopiedFlag] = useState(false);
  const [copiedCode, setCopiedCode] = useState(false);
  const [gofmtToast, setGofmtToast] = useState(false);
  const [ran, setRan] = useState(false);
  const snippetRef = useRef<HTMLElement | null>(null);
  const codeId = "lab-" + useId().replace(/[^a-zA-Z0-9_-]/g, "");

  // Watch real Codapi runs. Auto-unlock only on a clean build whose output
  // contains `expect`; otherwise just record that a run happened.
  useEffect(() => {
    const host = snippetRef.current;
    if (!host) return;
    const onResult = (e: Event) => {
      const d = (e as CustomEvent).detail as
        | { ok?: boolean; stdout?: string }
        | undefined;
      setRan(true);
      if (captured) return;
      if (!expect || (d?.ok && (d.stdout ?? "").includes(expect))) {
        setCaptured(true);
        recordLab(title, flag);
        playFlag();
        triggerConfetti();
        onCapture?.(flag, revealed);
      }
    };
    host.addEventListener("result", onResult as EventListener);
    return () => host.removeEventListener("result", onResult as EventListener);
  }, [captured, expect, flag, revealed, onCapture, title]);

  const revealManually = () => {
    setCaptured(true);
    recordLab(title, flag);
    playFlag();
    triggerConfetti();
    onCapture?.(flag, revealed);
  };

  const copyFlagToClipboard = async () => {
    try {
      await navigator.clipboard.writeText(flag);
      setCopiedFlag(true);
      setTimeout(() => setCopiedFlag(false), 2000);
    } catch {
      /* clipboard blocked */
    }
  };

  const resetStarter = () => {
    if (!starter) return;
    const el = document.getElementById(codeId);
    if (el) {
      const codeEl = el.querySelector("code") || el;
      codeEl.innerHTML = highlightGo(starter.replace(/^\n+|\n+$/g, ""));
    }
    playClick();
  };

  const handleGofmt = () => {
    const el = document.getElementById(codeId);
    if (!el) return;
    const text = el.textContent ?? "";
    const { formatted } = formatGo(text);
    const codeEl = el.querySelector("code") || el;
    codeEl.innerHTML = highlightGo(formatted);
    playClick();
    setGofmtToast(true);
    setTimeout(() => setGofmtToast(false), 1400);
  };

  return (
    <section className="lab">
      <div className="lab-head">
        <span className="lab-kicker">Lab — Capture the Flag</span>
        <div className="lab-tags">
          <span className="lab-tag">{ARCH_LABEL[archetype]}</span>
          {verify && (
            <span className={`lab-tag lab-verify lab-verify-${verify}`} title={VERIFY_TIP[verify]}>
              {VERIFY_LABEL[verify]}
            </span>
          )}
          <span className={`lab-tag lab-diff-${difficulty}`}>{difficulty}</span>
          <span className="lab-tag lab-pts">{points} pts</span>
        </div>
      </div>
      <h3 className="lab-title">{title}</h3>
      {objective && (
        <p className="lab-objective">
          <strong>Objective.</strong> {objective}
        </p>
      )}
      {children && <div className="lab-brief">{children}</div>}

      {starter && (
        <div className="lab-starter gb-ide-window" style={{ position: "relative" }}>
          {gofmtToast && (
            <div className="gb-gofmt-toast">
              ⚡ gofmt applied
            </div>
          )}
          <div className="lab-starter-bar gb-ide-bar">
            <div className="gb-ide-left">
              <span className="gb-ide-dots">
                <i className="gb-dot-r" />
                <i className="gb-dot-y" />
                <i className="gb-dot-g" />
              </span>
              <div className="gb-ide-tab">
                <span className="gb-ide-folder">📁 lab / </span>
                <span className="gb-ide-file">📄 starter.go</span>
              </div>
            </div>
            <div className="gb-ide-right">
              <button
                className="lab-reset-btn"
                onClick={resetStarter}
                type="button"
                title="Reset starter code"
              >
                ↺ Reset
              </button>
              <button
                className="lab-reset-btn"
                onClick={handleGofmt}
                type="button"
                title="Format with gofmt (⌘S / Ctrl+S)"
              >
                ⚡ Format
              </button>
              <button
                className="gb-ide-copy"
                onClick={async () => {
                  const el = document.getElementById(codeId);
                  if (el) {
                    await navigator.clipboard.writeText(el.textContent ?? "");
                    setCopiedCode(true);
                    setTimeout(() => setCopiedCode(false), 1400);
                  }
                }}
                type="button"
                aria-label="Copy code"
              >
                {copiedCode ? "Copied ✓" : "Copy"}
              </button>
              <span className="gb-ide-lang">GO 1.26</span>
              <span className="ply-hint">runnable</span>
            </div>
          </div>
          <pre className="lab-code" id={codeId} spellCheck={false}>
            <code dangerouslySetInnerHTML={{ __html: highlightGo(starter.replace(/^\n+|\n+$/g, "")) }} />
          </pre>
          <div className="lab-snippet">
            {createElement("codapi-snippet", {
              ref: snippetRef,
              sandbox: "go",
              editor: "basic",
              selector: `#${codeId}`,
            })}
          </div>
        </div>
      )}

      {verifier && (
        <p className="lab-verifier">
          <span className="lab-verifier-tag">verifier</span>
          {verifier}
        </p>
      )}

      {hints.length > 0 && (
        <div className="lab-hints">
          {hints.map((h, i) =>
            i < revealed ? (
              <p key={i} className="lab-hint-text">
                <span className="lab-hint-n">Hint {i + 1}</span>
                {h}
              </p>
            ) : i === revealed ? (
              <button
                key={i}
                className="lab-hint-btn"
                onClick={() => setRevealed((r) => r + 1)}
                type="button"
              >
                Reveal hint {i + 1}
                <span className="lab-hint-cost">−{hintCost} pts</span>
              </button>
            ) : null
          )}
        </div>
      )}

      <div className="lab-run">
        {captured ? (
          <span className="lab-run-state">Flag unlocked</span>
        ) : (
          <div className="lab-actions-row">
            <button className="lab-run-btn" onClick={revealManually} type="button">
              {expect && starter ? "Verify & Unlock Flag" : "Reveal Flag"}
            </button>
            {expect && starter && (
              <span className="lab-run-note">
                {ran
                  ? "Output not matching yet — fix the code or click Verify & Unlock."
                  : "Edit the code and click Run above, or click Verify & Unlock."}
              </span>
            )}
          </div>
        )}
        {revealed > 0 && !captured && (
          <span className="lab-run-note">{revealed} hint(s) used</span>
        )}
      </div>

      {captured && (
        <div className="lab-flag">
          <div className="lab-flag-header">
            <span className="lab-flag-label">Flag captured</span>
            <button
              className="lab-flag-copy"
              onClick={copyFlagToClipboard}
              type="button"
            >
              {copiedFlag ? "Copied" : "Copy Flag"}
            </button>
          </div>
          <code className="lab-flag-code">{flag}</code>
          <p className="lab-flag-note">
            {expect && starter
              ? "Verified — your code built clean and satisfied the verification criteria."
              : "Completed on the honor system. Check your solution against the objective and hints above."}
          </p>
        </div>
      )}
    </section>
  );
}

type ScoreItem = {
  label: string;
  kind?: "quiz" | "exercise" | "lab";
  points?: number;
  done?: boolean;
};

/** End-of-chapter progress panel. */
export function Scoreboard({
  points,
  total,
  streak,
  items = [],
  flag,
}: {
  points?: number;
  total?: number;
  streak?: number;
  items?: ScoreItem[];
  flag?: { label: string; captured?: boolean; points?: number };
}) {
  const all: ScoreItem[] = [
    ...items,
    ...(flag
      ? [
          {
            label: flag.label,
            kind: "lab" as const,
            points: flag.points ?? 50,
            done: flag.captured,
          },
        ]
      : []),
  ];
  const computedTotal =
    total ?? all.reduce((s, i) => s + (i.points ?? 10), 0);
  const computedPoints =
    points ?? all.reduce((s, i) => s + (i.done ? i.points ?? 10 : 0), 0);
  const pct = computedTotal
    ? Math.round((computedPoints / computedTotal) * 100)
    : 0;

  const [w, setW] = useState(0);
  useEffect(() => {
    const t = setTimeout(() => setW(pct), 120);
    return () => clearTimeout(t);
  }, [pct]);

  return (
    <section className="sb">
      <div className="sb-head">
        <span className="sb-kicker">Scoreboard</span>
        {typeof streak === "number" && (
          <span className="sb-streak">{streak} day streak</span>
        )}
      </div>
      <div className="sb-score">
        <span className="sb-pts">{computedPoints}</span>
        <span className="sb-of">/ {computedTotal} pts</span>
        <span className="sb-pct">{pct}%</span>
      </div>
      <div className="sb-track">
        <div className="sb-fill" style={{ width: `${w}%` }} />
      </div>
      <ul className="sb-items">
        {all.map((it, i) => (
          <li
            key={i}
            className={`sb-item ${it.done ? "done" : ""} ${
              it.kind === "lab" ? "sb-lab" : ""
            }`}
          >
            <span className="sb-check">{it.done ? "✓" : "○"}</span>
            <span className="sb-label">{it.label}</span>
            <span className="sb-ip">{it.points ?? 10}</span>
          </li>
        ))}
      </ul>
    </section>
  );
}

